import { NextRequest, NextResponse } from "next/server";
import { streamText } from "ai";
import { openai } from "@ai-sdk/openai";

export async function POST(req: NextRequest) {
  const body = await req.json();
  const { type, data } = body;

  if (!type || !data) {
    return NextResponse.json({ error: "type?data?????" }, { status: 400 });
  }

  let prompt = "";

  if (type === "individual") {
    const { memberNumber, gender, chartData, arrowStats } = data;
    const genderLabel = gender === "MALE" ? "??" : "??";
    const recentData = chartData
      .map(
        (d: { name: string; hitRate: number; hits: number; total: number }) =>
          `${d.name}: ${d.hits}/${d.total}? (${d.hitRate}%)`
      )
      .join("?");
    const arrowData = arrowStats
      .map(
        (a: { arrowNumber: number; hits: number; total: number }) =>
          `${a.arrowNumber}??: ${a.hits}/${a.total}?`
      )
      .join("?");

    prompt = `????????????????????????????????????????????200????????????????

??: ${genderLabel} No.${memberNumber}
????????: ${recentData}
?????: ${arrowData}

????????????????????????????`;
  } else if (type === "team") {
    const { tournamentName, roundStats, arrowStats } = data;
    const roundData = roundStats
      .map(
        (r: { label: string; hits: number; total: number; hitRate: number }) =>
          `${r.label}: ${r.hits}/${r.total}? (${r.hitRate}%)`
      )
      .join("?");
    const arrowData = arrowStats
      .map(
        (a: { arrowNumber: number; hits: number; total: number; hitRate: number }) =>
          `${a.arrowNumber}??: ${a.hits}/${a.total}? (${a.hitRate}%)`
      )
      .join("?");

    prompt = `??????????????????????????????????????????????????200????????????????

??: ${tournamentName}
?????: ${roundData}
?????: ${arrowData}

??????????????????????????????`;
  } else {
    return NextResponse.json({ error: "???type??" }, { status: 400 });
  }

  const result = streamText({
    model: openai("gpt-4o-mini"),
    prompt,
  });

  return result.toTextStreamResponse();
}
